export type LegacyDomain = (typeof LEGACY_DOMAINS)[number];

export interface LegacyResourceCatalogEntry<
  Domain extends LegacyDomain = LegacyDomain,
  Resource extends string = string,
> {
  readonly domain: Domain;
  readonly resource: Resource;
  readonly path: `/business/${Domain}/${Resource}`;
  readonly menuName: `legacy.${Domain}.${Resource}`;
  readonly titleKey: `legacy.resource.${Resource}.title`;
  readonly domainTitleKey: `legacy.domain.${Domain}`;
  readonly routePermission: `/business/${Domain}/${Resource}`;
  readonly listPermission: `/business/${Domain}/${Resource}/permissions/list`;
  readonly readPermission: `/business/${Domain}/${Resource}/permissions/read`;
  readonly createPermission: `/business/${Domain}/${Resource}/permissions/create`;
  readonly updatePermission: `/business/${Domain}/${Resource}/permissions/update`;
  readonly deletePermission: `/business/${Domain}/${Resource}/permissions/delete`;
}

function resource<const Domain extends LegacyDomain, const Resource extends string>(
  domain: Domain,
  name: Resource,
): LegacyResourceCatalogEntry<Domain, Resource> {
  return {
    domain,
    resource: name,
    path: `/business/${domain}/${name}`,
    menuName: `legacy.${domain}.${name}`,
    titleKey: `legacy.resource.${name}.title`,
    domainTitleKey: `legacy.domain.${domain}`,
    routePermission: `/business/${domain}/${name}`,
    listPermission: `/business/${domain}/${name}/permissions/list`,
    readPermission: `/business/${domain}/${name}/permissions/read`,
    createPermission: `/business/${domain}/${name}/permissions/create`,
    updatePermission: `/business/${domain}/${name}/permissions/update`,
    deletePermission: `/business/${domain}/${name}/permissions/delete`,
  };
}

