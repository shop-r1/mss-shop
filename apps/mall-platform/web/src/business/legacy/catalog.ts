const resourcesByPath = new Map<string, LegacyResourceEntry>(
  LEGACY_RESOURCES.map((entry) => [entry.path, entry]),
);

const resourcesByName = new Map<string, LegacyResourceEntry>(
  LEGACY_RESOURCES.map((entry) => [entry.resource, entry]),
);

export function findLegacyResourceByPath(pathname: string): LegacyResourceEntry | undefined {
  const normalized = pathname.length > 1 ? pathname.replace(/\/+$/, '') : pathname;
  return resourcesByPath.get(normalized);
}

export function findLegacyResourceByName(name: string): LegacyResourceEntry | undefined {
  return resourcesByName.get(name);
}
